"""Generates the token files of both apps from design/design-tokens.json.

usage:
    python design/generate_tokens.py            write the generated files
    python design/generate_tokens.py --check    fail (exit 1) if a generated file is out of date
    python design/generate_tokens.py --hams <path to hams/ui_kit/theme.py>
                                                fail if Hams' palettes differ from the tokens

Writes:
    engine/MosaikUi/Tokens.Light.xaml, engine/MosaikUi/Tokens.Dark.xaml   resource dictionaries (frozen brushes)
    engine/MosaikUi/UiTokens.g.cs                                       measures, fixed tones, key names
    design/generated/hams-theme-values.json                            Hams' palettes (shared + Hams' accent)

Standard library only. Hams' theme.py is read as text (ast), never imported.
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "design-tokens.json"
APP = "capture"
HEADER = "Generated by design/generate_tokens.py from design/design-tokens.json. Do not edit."


def key(name: str) -> str:
    """WINDOW_BG -> Mui.WindowBg (the resource key of a token)."""
    return "Mui." + pascal(name)


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.lower().split("_"))


def palettes(tokens: dict, app: str) -> dict:
    """Shared palettes plus the app's own tokens, per mode."""
    result = {}
    for mode in ("light", "dark"):
        palette = dict(tokens["shared"][mode])
        palette.update(tokens["apps"][app][mode])
        result[mode] = dict(sorted(palette.items()))
    return result


def xaml(tokens: dict, mode: str) -> str:
    palette = palettes(tokens, APP)[mode]
    lines = [
        "<!-- " + HEADER + " -->",
        '<ResourceDictionary x:Class="MosaikCapture.Engine.MosaikUi.Tokens' + mode.capitalize() + '" x:ClassModifier="internal"',
        '                    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
        '                    xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"',
        '                    xmlns:po="http://schemas.microsoft.com/winfx/2006/xaml/presentation/options"',
        '                    mc:Ignorable="po">',
        "",
        "    <!-- Theme tokens (" + mode + "): the names and values of Hams, the accent of this app. -->",
    ]
    for name, value in palette.items():
        lines.append(f'    <SolidColorBrush x:Key="{key(name)}" Color="{value}" po:Freeze="True" />')
    lines += ["", "    <!-- Fixed tones: the same in both themes. -->"]
    for name, value in tokens["fixed"].items():
        lines.append(f'    <SolidColorBrush x:Key="{key(name)}" Color="{value}" po:Freeze="True" />')
    lines += ["", "    <!-- Legacy keys of the windows before the redesign (until phase 5). -->"]
    for name, value in tokens["legacy"][mode].items():
        lines.append(f'    <SolidColorBrush x:Key="{name}" Color="{value}" po:Freeze="True" />')
    lines += ["", "</ResourceDictionary>", ""]
    return "\r\n".join(lines)


def number(value) -> str:
    text = repr(float(value)) if isinstance(value, float) else str(value)
    return text


def csharp(tokens: dict) -> str:
    out = [
        "// <auto-generated>",
        "// " + HEADER,
        "// </auto-generated>",
        "",
        "namespace MosaikCapture.Engine.MosaikUi;",
        "",
        "/// <summary>Measures (logical pixels), fixed tones and resource keys of the design tokens, as in Hams' theme.py.</summary>",
        "internal static partial class UiTokens",
        "{",
    ]

    def block(name: str, summary: str, values: dict, kind: str = "double") -> None:
        out.append(f"    /// <summary>{summary}</summary>")
        out.append(f"    internal static partial class {name}")
        out.append("    {")
        for item, value in values.items():
            out.append(f"        public const {kind} {pascal(item)} = {number(value)};")
        out.append("    }")
        out.append("")

    block("Space", "Spacing on a 4 px grid; the roles are the only values a layout uses.", tokens["space"])
    block("Radius", "Related radii: inner = outer minus the gap between them.", tokens["radius"])
    block("Depth", "Ink and watercolour: the side under a surface (a pressed control sinks by it) and the ink edge.", tokens["depth"])
    block("Height", "Control heights: only three, plus the key cap and the minimum row.", tokens["height"])

    palette = palettes(tokens, APP)
    names = list(palette["light"])
    out.append("    /// <summary>Resource keys of the theme tokens (both themes carry the same keys).</summary>")
    out.append("    internal static class Keys")
    out.append("    {")
    for name in names:
        out.append(f'        public const string {pascal(name)} = "{key(name)}";')
    for name in tokens["fixed"]:
        out.append(f'        public const string {pascal(name)} = "{key(name)}";')
    out.append("    }")
    out.append("")
    out.append("    /// <summary>Token names (as in Hams) of the theme palettes.</summary>")
    out.append("    internal static readonly string[] ThemeTokenNames =")
    out.append("    {")
    for name in names:
        out.append(f'        "{name}",')
    out.append("    };")
    out.append("")
    out.append("    /// <summary>Tones that do not change with the theme (ARGB), as colours and frozen brushes.</summary>")
    out.append("    internal static class Fixed")
    out.append("    {")
    for name, value in tokens["fixed"].items():
        argb = value.lstrip("#")
        a, r, g, b = (argb[i : i + 2] for i in (0, 2, 4, 6))
        out.append(f"        public static readonly Color {pascal(name)} = Color.FromArgb(0x{a}, 0x{r}, 0x{g}, 0x{b});")
    out.append("")
    for name in tokens["fixed"]:
        out.append(f"        public static readonly SolidColorBrush {pascal(name)}Brush = Frozen({pascal(name)});")
    out.append("")
    out.append("        static SolidColorBrush Frozen(Color color)")
    out.append("        {")
    out.append("            var brush = new SolidColorBrush(color);")
    out.append("            brush.Freeze();")
    out.append("            return brush;")
    out.append("        }")
    out.append("    }")
    out.append("")
    fonts = tokens["fonts"]
    out.append("    /// <summary>Font families: the rounded face (embedded) with its fallback, and the body face.</summary>")
    out.append("    internal static class FontNames")
    out.append("    {")
    out.append(f'        public const string Rounded = "{fonts["rounded"]["family"]}";')
    out.append(f'        public const string RoundedFile = "{fonts["rounded"]["file"]}";')
    out.append(f'        public const string RoundedFallback = "{fonts["rounded"]["fallback"]}";')
    out.append(f'        public const string Body = "{fonts["body"]["family"]}";')
    out.append("    }")
    out.append("}")
    out.append("")
    return "\r\n".join(out)


def hams_values(tokens: dict) -> str:
    data = {"$comment": HEADER + " Hams' palettes: shared tokens plus Hams' accent."}
    data.update(palettes(tokens, "hams"))
    return json.dumps(data, indent=2) + "\n"


def outputs(tokens: dict) -> dict:
    return {
        ROOT / "engine" / "MosaikUi" / "Tokens.Light.xaml": xaml(tokens, "light"),
        ROOT / "engine" / "MosaikUi" / "Tokens.Dark.xaml": xaml(tokens, "dark"),
        ROOT / "engine" / "MosaikUi" / "UiTokens.g.cs": csharp(tokens),
        ROOT / "design" / "generated" / "hams-theme-values.json": hams_values(tokens),
    }


def read_hams_palettes(theme_py: Path) -> dict:
    """The `_PALETTES` literal of Hams' Theme class, read with ast (Theme.LIGHT/DARK -> 'light'/'dark')."""
    tree = ast.parse(theme_py.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "Theme":
            for statement in node.body:
                target = statement.targets[0] if isinstance(statement, ast.Assign) else getattr(statement, "target", None)
                if isinstance(target, ast.Name) and target.id == "_PALETTES":
                    result = {}
                    for mode_node, palette_node in zip(statement.value.keys, statement.value.values, strict=True):
                        mode = mode_node.id.lower() if isinstance(mode_node, ast.Name) else ast.literal_eval(mode_node)
                        result[mode] = {k: v.upper() for k, v in ast.literal_eval(palette_node).items()}
                    return result
    raise SystemExit(f"no Theme._PALETTES in {theme_py}")


def main(argv: list[str]) -> int:
    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    if "--hams" in argv:
        hams = read_hams_palettes(Path(argv[argv.index("--hams") + 1]))
        ours = palettes(tokens, "hams")
        problems = []
        for mode in ("light", "dark"):
            for name in sorted(set(hams[mode]) | set(ours[mode])):
                if hams[mode].get(name) != ours[mode].get(name):
                    problems.append(f"{mode}/{name}: Hams {hams[mode].get(name)}, tokens {ours[mode].get(name)}")
        print("\n".join(problems) or "Hams' palettes match the tokens.")
        return 1 if problems else 0
    stale = []
    for path, text in outputs(tokens).items():
        current = path.read_bytes().decode("utf-8") if path.exists() else None
        if current == text:
            continue
        if "--check" in argv:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("out of date (run design/generate_tokens.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
